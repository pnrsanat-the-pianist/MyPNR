lines = data.split('\n')
rows = []

# Map months to their numeric values
months = {
    'Ağu': '08', 'Eyl': '09', 'Eki': '10', 'Kas': '11', 'Ara': '12', 'Oca': '01', 'Şub': '02'
}

def parse_date(date_str):
    try:
        parts = date_str.strip().split(' ')
        if len(parts) == 3:
            day = parts[0].zfill(2)
            month = months.get(parts[1], '01')
            year = parts[2]
            return f"{year}-{month}-{day}"
    except:
        pass
    return "2026-02-12" # Fallback

for line in lines:
    if not line.strip() or line.strip() == "1	PNR":
        continue
    
    parts = line.split('\t')
    if len(parts) < 7:
        continue
        
    date_raw = parts[0]
    student_name = parts[1].strip()
    branch = parts[2].strip()
    age_str = parts[3].strip()
    phone = parts[4].strip()
    parent_name = parts[5].strip()
    note_content = parts[6].strip()
    
    # Handle age (replace commas with dots)
    age = 0
    if age_str:
        try:
            age = float(age_str.replace(',', '.'))
        except:
            age = 0
            
    # Determine Source
    source = "Diğer"
    if "VERİMOR" in student_name.upper() or "VERIMOR" in student_name.upper():
        source = "Verimor"
        student_name = student_name.replace("VERİMOR", "").replace("VERIMOR", "").strip()
    elif "INSTAGTRAM" in student_name.upper() or "INSTAGRAM" in student_name.upper():
        source = "Instagram"
        student_name = student_name.replace("INSTAGTRAM", "").replace("INSTAGRAM", "").strip()
    elif "WHATSAPP" in student_name.upper():
        source = "Whatsapp"
        student_name = student_name.replace("WHATSAPP", "").strip()

    # If student name is empty, try to get it from note or parent name
    actual_student_name = student_name if student_name else parent_name
    
    # Format created_at
    created_at = parse_date(date_raw)
    
    # Create notes list for JSONB
    notes_list = []
    if note_content:
        notes_list.append({
            "id": "init_" + str(len(rows)),
            "user": "Sistem",
            "date": date_raw,
            "content": note_content
        })
    
    rows.append({
        'student_name': actual_student_name,
        'age': age,
        'branch': branch if branch else "Diğer",
        'parent_name': parent_name,
        'phone': phone,
        'source': source,
        'status': 'Takip',
        'notes': json.dumps(notes_list, ensure_ascii=False),
        'created_at': created_at
    })

# Write to CSV
with open('c:/Users/kaanc/AG_2026MyPNR/2026MyPNR/database/new_leads_import.csv', 'w', encoding='utf-8-sig', newline='') as f:
    writer = csv.DictWriter(f, fieldnames=['student_name', 'age', 'branch', 'parent_name', 'phone', 'source', 'status', 'notes', 'created_at'])
    writer.writeheader()
    writer.writerows(rows)

print(f"Successfully processed {len(rows)} leads.")
